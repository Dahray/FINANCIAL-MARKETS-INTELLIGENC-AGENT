"""QuantForecast and ForecastBacktest ORM models (Section 6 & Section 11)."""

from __future__ import annotations

from datetime import datetime
from typing import Any, Dict, List

from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, Numeric, String
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, JSONVariant
from app.models.user import new_uuid_str, utc_now


class QuantForecast(Base):
    """
    Deterministic statistical/ML forecast record generated by Agent 6 (Quantitative Analysis Agent).
    Strictly separated from historical performance (`is_forecast = True`).
    Stores Base Case, Bull Case, Bear Case, key assumptions, confidence level,
    and factors that could invalidate the forecast.
    """

    __tablename__ = "quant_forecasts"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_uuid_str)
    target_code: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    target_name: Mapped[str] = mapped_column(String(255), nullable=False)
    model_family: Mapped[str] = mapped_column(String(64), nullable=False)
    generated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utc_now, nullable=False, index=True
    )
    forecast_horizon_label: Mapped[str] = mapped_column(String(64), nullable=False)
    forecast_target_date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, index=True
    )

    last_historical_value: Mapped[float] = mapped_column(Numeric(20, 6), nullable=False)
    last_historical_date: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    # Mandatory Scenario Bands
    base_case: Mapped[float] = mapped_column(Numeric(20, 6), nullable=False)
    bull_case: Mapped[float] = mapped_column(Numeric(20, 6), nullable=False)
    bear_case: Mapped[float] = mapped_column(Numeric(20, 6), nullable=False)
    confidence_level_pct: Mapped[float] = mapped_column(Numeric(5, 2), nullable=False, default=80.0)

    key_assumptions: Mapped[List[str]] = mapped_column(JSONVariant, nullable=False, default=list)
    invalidation_factors: Mapped[List[str]] = mapped_column(
        JSONVariant, nullable=False, default=list
    )
    forecast_series_json: Mapped[List[Dict[str, Any]]] = mapped_column(
        JSONVariant, nullable=False, default=list
    )
    currency_or_unit: Mapped[str] = mapped_column(String(64), nullable=False)
    is_forecast: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    agent_name: Mapped[str] = mapped_column(
        String(64), nullable=False, default="AGENT_6_QUANT", index=True
    )
    predicted_direction: Mapped[str] = mapped_column(
        String(16), nullable=False, default="FLAT"
    )
    source_register_ids: Mapped[List[str]] = mapped_column(
        JSONVariant, nullable=False, default=list
    )



class ForecastBacktest(Base):
    """
    Walk-forward historical backtesting metrics comparing model predictions against actual outcomes.
    Required by Section 11 ('Backtest forecasting models and compare their predictions with actual outcomes').
    """

    __tablename__ = "forecast_backtests"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_uuid_str)
    forecast_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("quant_forecasts.id", ondelete="CASCADE"), nullable=False, index=True
    )
    target_code: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    model_family: Mapped[str] = mapped_column(String(64), nullable=False)
    backtest_window_start: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    backtest_window_end: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    n_splits: Mapped[int] = mapped_column(Integer, nullable=False)

    rmse: Mapped[float] = mapped_column(Numeric(20, 6), nullable=False)
    mae: Mapped[float] = mapped_column(Numeric(20, 6), nullable=False)
    mape_pct: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    directional_accuracy_pct: Mapped[float] = mapped_column(Numeric(10, 4), nullable=False)
    predicted_vs_actual_json: Mapped[List[Dict[str, Any]]] = mapped_column(
        JSONVariant, nullable=False, default=list
    )
    evaluated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utc_now, nullable=False
    )
